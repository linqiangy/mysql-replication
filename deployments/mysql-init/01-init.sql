-- bincat 元数据库初始化（docker-compose mysql-meta 容器首次启动执行）
-- 被监听的演示库与账号
CREATE DATABASE IF NOT EXISTS shop DEFAULT CHARSET utf8mb4;
CREATE USER IF NOT EXISTS 'bincat'@'%' IDENTIFIED BY 'bincat123';
GRANT REPLICATION SLAVE, REPLICATION CLIENT, SELECT ON *.* TO 'bincat'@'%';
GRANT ALL PRIVILEGES ON bincat_meta.* TO 'bincat'@'%';
GRANT SELECT ON shop.* TO 'bincat'@'%';
FLUSH PRIVILEGES;

-- 演示表
USE shop;
CREATE TABLE IF NOT EXISTS orders_2026 (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_no VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'created',
  pay_time DATETIME NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  remark VARCHAR(255) DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  email VARCHAR(128) DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
